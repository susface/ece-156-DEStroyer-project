//////////////////////////////////////////////////////////////
// 2. SP-BOX TABLE (mutable — populated by des_cpu_init)
//////////////////////////////////////////////////////////////

static u32 SP[8][64];

//////////////////////////////////////////////////////////////
// 3. PERMUTATION (internal)
//////////////////////////////////////////////////////////////

static u64 permute(u64 input, const int* table, int size, int inputBits) {
    u64 output = 0;
    for (int i = 0; i < size; i++) {
        output <<= 1;
        output |= (input >> (inputBits - table[i])) & 1;
    }
    return output;
}

//////////////////////////////////////////////////////////////
// 4. BUILD SP-BOX (internal)
//////////////////////////////////////////////////////////////

static void init_sp_boxes() {
    for (int box = 0; box < 8; box++) {
        for (int i = 0; i < 64; i++) {
            int row  = ((i & 0x20) >> 4) | (i & 0x01);
            int col  = (i >> 1) & 0x0F;
            u32 val  = (u32)S[box][row][col] << (28 - 4 * box);
            SP[box][i] = (u32)permute(val, P, 32, 32);
        }
    }
}

//////////////////////////////////////////////////////////////
// 5. EXPANSION (internal, 32 → 48)
//////////////////////////////////////////////////////////////

static u64 expand(u32 R) {
    return permute(R, E, 48, 32);
}

//////////////////////////////////////////////////////////////
// 6. FEISTEL (internal, SP-box optimized)
//////////////////////////////////////////////////////////////

static u32 feistel(u32 R, u64 K) {
    u64 x = expand(R) ^ K;
    return
        SP[0][(x >> 42) & 0x3F] ^
        SP[1][(x >> 36) & 0x3F] ^
        SP[2][(x >> 30) & 0x3F] ^
        SP[3][(x >> 24) & 0x3F] ^
        SP[4][(x >> 18) & 0x3F] ^
        SP[5][(x >> 12) & 0x3F] ^
        SP[6][(x >>  6) & 0x3F] ^
        SP[7][ x        & 0x3F];
}

//////////////////////////////////////////////////////////////
// 7. PUBLIC API
//////////////////////////////////////////////////////////////

void des_cpu_init() {
    init_sp_boxes();
}

void generate_subkeys(uint64_t key, uint64_t subkeys[16]) {
    u64 permuted = permute(key, PC1, 56, 64);
    u32 C = (permuted >> 28) & 0x0FFFFFFF;
    u32 D =  permuted        & 0x0FFFFFFF;

    for (int i = 0; i < 16; i++) {
        C = ((C << SHIFTS[i]) | (C >> (28 - SHIFTS[i]))) & 0x0FFFFFFF;
        D = ((D << SHIFTS[i]) | (D >> (28 - SHIFTS[i]))) & 0x0FFFFFFF;
        u64 combined = ((u64)C << 28) | D;
        subkeys[i] = permute(combined, PC2, 48, 56);
    }
}

uint64_t des_encrypt(uint64_t block, uint64_t subkeys[16]) {
    block = permute(block, IP, 64, 64);
    u32 L = (u32)(block >> 32);
    u32 R = (u32)(block & 0xFFFFFFFF);
    for (int i = 0; i < 16; i++) {
        u32 temp = R;
        R = L ^ feistel(R, subkeys[i]);
        L = temp;
    }
    return permute(((u64)R << 32) | L, FP, 64, 64);
}

uint64_t des_decrypt(uint64_t block, uint64_t subkeys[16]) {
    block = permute(block, IP, 64, 64);
    u32 L = (u32)(block >> 32);
    u32 R = (u32)(block & 0xFFFFFFFF);
    for (int i = 15; i >= 0; i--) {
        u32 temp = R;
        R = L ^ feistel(R, subkeys[i]);
        L = temp;
    }
    return permute(((u64)R << 32) | L, FP, 64, 64);
}

uint64_t double_des_encrypt(uint64_t plaintext, uint64_t key1, uint64_t key2) {
    uint64_t sub1[16], sub2[16];
    generate_subkeys(key1, sub1);
    generate_subkeys(key2, sub2);
    return des_encrypt(des_encrypt(plaintext, sub1), sub2);
}
